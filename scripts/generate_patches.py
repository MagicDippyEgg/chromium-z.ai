#!/usr/bin/env python3
"""
Apply the Halcyon changes to the upstream Chromium files in
/tmp/halcyon-patch-work/chromium-pin/ and emit clean, line-accurate
diffs into /home/z/my-project/chromium-z.ai/patches/.

This script is the source of truth for the patches. It reads each
upstream file, applies a small surgical change, writes the file back,
and then runs `git diff` to produce the patch file.

The advantage of generating patches this way is that the patches are
GUARANTEED to apply cleanly against the pinned revision (because they
were generated BY applying the changes against that revision).

Run:
    python3 /home/z/my-project/scripts/generate_patches.py
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

WORK = Path("/tmp/halcyon-patch-work/chromium-pin")
PATCHES_DIR = Path("/home/z/my-project/chromium-z.ai/patches")

PINNED_SHA = "ff897141277d798d72ea3ae0a94ff3a51956b267"
PINNED_VERSION = "159.0.8142.0"


def read(rel_path: str) -> str:
    return (WORK / rel_path).read_text(encoding="utf-8")


def write(rel_path: str, content: str) -> None:
    (WORK / rel_path).write_text(content, encoding="utf-8")


def replace_once(content: str, old: str, new: str) -> str:
    """Replace `old` with `new` in `content`. Error if not found exactly once."""
    count = content.count(old)
    if count != 1:
        raise ValueError(f"Expected exactly 1 occurrence of {old[:60]!r}, found {count}")
    return content.replace(old, new)


def git(args, cwd=WORK):
    return subprocess.run(
        ["git", "-C", str(cwd), *args],
        check=True, capture_output=True, text=True)


def emit_patch(name: str, files: list[str], commit_msg: str) -> None:
    """Generate a patch file from the staged changes, then commit so the
    next patch's diff is generated against THIS state (not the baseline).

    This is the key invariant: each patch's diff line numbers MUST match
    the file state AFTER all previous patches have been applied. We
    achieve this by committing each patch's changes to a temporary
    branch, so the next patch's diff is between (previous-patches-applied)
    and (previous-patches-applied + this-patch).
    """
    out_path = PATCHES_DIR / name
    # Add the changes
    git(["add"] + files)
    diff = git(["diff", "--cached", "--no-color", "--"] + files).stdout
    # Commit so HEAD now reflects this patch applied. The next patch's
    # diff will be between (HEAD-with-this-patch) and (working-tree-with-next-patch).
    git(["commit", "-m", commit_msg, "--"] + files)
    # Write the patch with a proper header
    header = f"""From: Halcyon Browser Project <halcyon@local>
Date: Tue, 4 Nov 2026 00:00:00 +0000
Subject: [PATCH] (generated against Chromium {PINNED_SHA[:12]})

Pinned Chromium revision: {PINNED_SHA}
                       (Chromium {PINNED_VERSION}, main HEAD at pin time)

This patch was generated by scripts/generate_patches.py. Re-run that
script against the pinned revision to regenerate this file.

"""
    out_path.write_text(header + diff, encoding="utf-8")
    print(f"  generated: {out_path.name} ({len(diff.splitlines())} diff lines)")


