# ---------------------------------------------------------------------------
# Patch 5: browser_view_replace_tab_strip — conditionally use HalcyonTabStrip
#
# The current Chromium architecture wraps TabStrip inside a
# HorizontalTabStripRegionView, and the actual TabStrip instantiation is
# deep inside CreateHorizontalTabStripRegionView(). A full swap requires
# either replacing that factory function or wiring through the region
# view. The minimal, safe patch is to add an alternative HalcyonTabStrip
# controller that the Halcyon-specific code can use, and a feature-flag
# branch inside the existing tab-strip initialization that prefers the
# HalcyonTabStrip when kHalcyonUI is on. The existing TabStrip code path
# is preserved unchanged for the upstream case.
# ---------------------------------------------------------------------------

def patch_5_browser_view_replace_tab_strip():
    print("=== Patch 5: browser_view_replace_tab_strip.patch ===")

    p = "chrome/browser/ui/views/frame/browser_view.cc"
    content = read(p)
    # Add the HalcyonTabStrip include after the existing tab_strip.h include.
    # Look for the actual include line in the file.
    if '#include "chrome/browser/ui/views/tabs/tab_strip.h"' not in content:
        # The file may not directly include tab_strip.h anymore; fall back
        # to including it next to the horizontal_tab_strip_region_view.h include.
        anchor = '#include "chrome/browser/ui/views/tabs/horizontal_tab_strip_region_view.h"'
        if anchor not in content:
            raise ValueError("Couldn't find a tab strip anchor include in browser_view.cc")
        content = replace_once(
            content,
            anchor + "\n",
            anchor + "\n"
            '#include "chrome/browser/ui/views/tabs/halcyon_tab_strip.h"\n'
            '#include "chrome/browser/ui/views/tabs/halcyon_tab_strip_controller.h"\n',
        )
    else:
        content = replace_once(
            content,
            '#include "chrome/browser/ui/views/tabs/tab_strip.h"\n',
            '#include "chrome/browser/ui/views/tabs/tab_strip.h"\n'
            '#include "chrome/browser/ui/views/tabs/halcyon_tab_strip.h"\n'
            '#include "chrome/browser/ui/views/tabs/halcyon_tab_strip_controller.h"\n',
        )

    # Branch the tab strip region view initialization. The actual upstream
    # code creates a HorizontalTabStripRegionView and then conditionally
    # initializes a vertical strip. The simplest place to add the Halcyon
    # branch is right before horizontal_tab_strip_region_view_->InitializeTabStrip();
    # — if Halcyon is on, we instead instantiate a HalcyonTabStrip and add it
    # in place of the horizontal strip. (This is a structural simplification;
    # the full HalcyonBrowserView replacement would handle this in the
    # Halcyon code itself.)
    content = replace_once(
        content,
        """  } else {
    horizontal_tab_strip_region_view_->InitializeTabStrip();
  }""",
        """  } else {
    if (base::FeatureList::IsEnabled(features::kHalcyonUI)) {
      // Halcyon: instantiate a HalcyonTabStrip in place of the upstream
      // TabStrip. The HalcyonTabStrip is a flat (no rounded corners) tab
      // strip where the active tab's background matches the page
      // background — see chrome/browser/ui/views/tabs/halcyon_tab_strip.h.
      // It is owned by horizontal_tab_strip_region_view_.
      halcyon_tabstrip_controller_ =
          std::make_unique<HalcyonTabStripController>(browser());
      halcyon_tabstrip_ = horizontal_tab_strip_region_view_->AddChildView(
          std::make_unique<HalcyonTabStrip>(
              halcyon_tabstrip_controller_.get()));
    } else {
      horizontal_tab_strip_region_view_->InitializeTabStrip();
    }
  }""",
    )
    write(p, content)

    emit_patch("browser_view_replace_tab_strip.patch", [
        "chrome/browser/ui/views/frame/browser_view.cc",
    ], "browser_view: use HalcyonTabStrip when kHalcyonUI is enabled")


