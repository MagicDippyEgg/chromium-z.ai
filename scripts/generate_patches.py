def main():
    PATCHES_DIR.mkdir(exist_ok=True)

    print("Generating Halcyon integration patches against pinned Chromium revision")
    print(f"  pinned SHA:     {PINNED_SHA}")
    print(f"  pinned version: {PINNED_VERSION}")
    print(f"  work dir:       {WORK}")
    print(f"  output dir:     {PATCHES_DIR}")
    print()

    # Configure git for commits (the runner doesn't have a global identity)
    git(["config", "user.email", "halcyon@local"])
    git(["config", "user.name", "Halcyon Patches"])

    # Reset the working tree to the pinned revision (not HEAD — HEAD may
    # have advanced if a previous run committed patches). We reset hard
    # to the pinned SHA, then clean untracked files.
    print(f"  resetting to pinned revision {PINNED_SHA[:12]}...")
    git(["reset", "--hard", PINNED_SHA])
    git(["clean", "-fdx"])

    # Verify we're at the pinned revision.
    actual_sha = subprocess.run(
        ["git", "-C", str(WORK), "rev-parse", "HEAD"],
        check=True, capture_output=True, text=True).stdout.strip()
    if actual_sha != PINNED_SHA:
        print(f"  ERROR: expected {PINNED_SHA}, got {actual_sha}")
        sys.exit(1)
    print(f"  confirmed at: {actual_sha[:12]}")
    print()

    patch_1_gyp_enable_halcyon()
    patch_2_chrome_command_ids()
    patch_3_theme_use_halcyon()
    patch_4_browser_view_replace_toolbar()
    patch_5_browser_view_replace_tab_strip()
    patch_6_context_menu_add_margin_note()
    patch_7_webui_register_halcyon_ntp()
    patch_8_webui_register_halcyon_pages()

    print()
    print("All 8 patches generated.")
    print("Each patch is staged on top of the previous one; together they apply")
    print("in order 1 → 8 against the pinned revision.")


if __name__ == "__main__":
    main()
